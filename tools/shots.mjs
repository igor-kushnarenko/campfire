// Headless-проверка сцены. Запуск: node tools/shots.mjs http://localhost:4173/ [outdir]
import { chromium } from 'playwright-core';
const url = process.argv[2] || 'http://localhost:4173/';
const out = process.argv[3] || '/workspace/campfire_layers';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
p.on('response', (r) => r.status() >= 400 && errs.push(r.status() + ' ' + r.url()));
const st = () => p.evaluate(() => window.__campfire.state());
const wake = async () => { await p.mouse.move(1700, 1000); await p.mouse.move(1710, 1005); await p.waitForTimeout(300); };
await p.goto(url + '?fuel=2400'); await p.evaluate(() => localStorage.clear()); await p.reload();
await p.waitForTimeout(1500); await p.mouse.click(700, 300);
await p.waitForTimeout(12000);
console.log('full', JSON.stringify(await st()));
await p.screenshot({ path: out + '/v4_full_scene.png' });
await p.screenshot({ path: out + '/v4_lantern.png', clip: { x: 300, y: 120, width: 260, height: 340 } });
await p.screenshot({ path: out + '/v4_lake.png', clip: { x: 760, y: 470, width: 1000, height: 300 } });
await p.screenshot({ path: out + '/v4_fire_area.png', clip: { x: 560, y: 560, width: 800, height: 420 } });
await wake(); await p.click('#volbtn'); await p.waitForTimeout(300);
const hud = await p.locator('#hud').boundingBox();
await p.screenshot({ path: out + '/v4_ui_volumes.png', clip: { x: hud.x - 20, y: hud.y - 20, width: hud.width + 40, height: hud.height + 40 } });
await wake(); await p.click('#volbtn');
await wake(); await p.click('#rain'); await p.mouse.move(100, 100);
await p.waitForTimeout(9000);
console.log('rain', JSON.stringify(await st()));
await p.screenshot({ path: out + '/v4_rain.png' });
await p.screenshot({ path: out + '/v4_rain_lake.png', clip: { x: 760, y: 470, width: 1000, height: 300 } });
await wake(); await p.click('#rain'); // выключить дождь
await wake(); await p.click('#douse');
await p.evaluate(() => window.__campfire.setSpeed(60)); await p.waitForTimeout(4000);
console.log('douse x60', JSON.stringify(await st()));
await p.screenshot({ path: out + '/v4_after_douse.png', clip: { x: 460, y: 300, width: 1000, height: 700 } });
await p.reload(); await p.waitForTimeout(1500);
console.log('rain persisted after reload (expect false):', JSON.stringify((await st()).rain));
console.log('errors:', errs); await b.close();
